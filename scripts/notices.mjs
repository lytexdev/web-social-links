import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = '.output/server/node_modules'
if (!existsSync(root)) {
  process.stderr.write('Run pnpm build first, the notices list the packages bundled into .output\n')
  process.exit(1)
}

function packages(directory) {
  const found = []
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue
    const path = join(directory, entry.name)
    if (entry.name.startsWith('@')) found.push(...packages(path))
    else if (existsSync(join(path, 'package.json'))) found.push(path)
  }
  return found
}

const rows = packages(root)
  .map((path) => JSON.parse(readFileSync(join(path, 'package.json'), 'utf8')))
  .filter((manifest) => manifest.name && manifest.version)
  .map((manifest) => {
    const license =
      typeof manifest.license === 'string'
        ? manifest.license
        : (manifest.license?.type ?? 'see package')
    return `| ${manifest.name} | ${manifest.version} | ${license} |`
  })
  .sort()

const head = readFileSync('THIRD_PARTY_NOTICES.md', 'utf8').split('## Bundled runtime packages')[0]
writeFileSync(
  'THIRD_PARTY_NOTICES.md',
  `${head}## Bundled runtime packages\n\nGenerated by \`pnpm notices\` from the server bundle that ships in the container image.\n\n| Package | Version | License |\n| --- | --- | --- |\n${[...new Set(rows)].join('\n')}\n`,
)
process.stdout.write(`${rows.length} packages listed\n`)
